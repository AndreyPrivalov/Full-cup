/**
 * Сортирует массив категорий по популярности за последний год.
 */
export function sortCategoriesByPopularity(categories = []) {
  if (!categories?.length) return [];
  return [...categories].sort((a, b) => {
    const rankA = CATEGORY_POPULARITY_ORDER.indexOf(a.name);
    const rankB = CATEGORY_POPULARITY_ORDER.indexOf(b.name);
    const effA = rankA === -1 ? 999 : rankA;
    const effB = rankB === -1 ? 999 : rankB;
    if (effA !== effB) return effA - effB;
    return a.name.localeCompare(b.name, "ru");
  });
}

/**
 * Normalizes thousands separators (spaces between digits) within text:
 * E.g. '1 000' -> '1000', '1 000 000' -> '1000000'.
 */
export function normalizeNumberSpaces(str) {
  if (!str || typeof str !== "string") return "";
  let res = str;
  const regex = /(?<=(?:^|[^a-zA-Zа-яёА-ЯЁ0-9_])\d{1,3})\s+(?=\d{2,4}(?:[^a-zA-Zа-яёА-ЯЁ0-9_]|$))/g;
  while (regex.test(res)) {
    res = res.replace(regex, "");
  }
  return res;
}

/**
 * Formats standalone numbers in text with thousands separators:
 * E.g. '15000 кофе' -> '15 000 кофе', '1000 + 50000' -> '1 000 + 50 000'.
 */
export function formatNumbersInText(text) {
  if (!text || typeof text !== "string") return "";
  const clean = normalizeNumberSpaces(text);
  const regex = /(?:^|(?<=[^a-zA-Zа-яёА-ЯЁ0-9_]))(\d+(?:[.,]\d+)?)(?![a-zA-Zа-яёА-ЯЁ0-9_])/g;
  return clean.replace(regex, (match) => {
    const parts = match.split(/([.,])/);
    const intPart = parts[0];
    const decPart = parts.length > 1 ? parts.slice(1).join("") : "";
    const formattedInt = intPart.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
    return formattedInt + decPart;
  });
}

/**
 * Formats text with numbers while recalculating and preserving the cursor position.
 */
export function formatTextWithCursor(text, cursorPos = 0) {
  if (!text || typeof text !== "string") {
    return { formatted: "", newCursorPos: 0 };
  }

  const beforeCursor = text.slice(0, cursorPos);
  const trimmedBefore = beforeCursor.trimEnd();
  const trailingSpaces = beforeCursor.length - trimmedBefore.length;
  let nonSpacesBefore = 0;
  for (let i = 0; i < trimmedBefore.length; i++) {
    if (trimmedBefore[i] !== " ") nonSpacesBefore++;
  }

  const formatted = formatNumbersInText(text);

  let newCursorPos = 0;
  let seen = 0;
  if (nonSpacesBefore === 0) {
    newCursorPos = Math.min(trailingSpaces, formatted.length);
  } else {
    while (newCursorPos < formatted.length && seen < nonSpacesBefore) {
      if (formatted[newCursorPos] !== " ") seen++;
      newCursorPos++;
    }
    for (
      let s = 0;
      s < trailingSpaces && newCursorPos < formatted.length && formatted[newCursorPos] === " ";
      s++
    ) {
      newCursorPos++;
    }
  }

  return { formatted, newCursorPos };
}

/**
 * Evaluates an arithmetic expression containing numbers and operators (+, -, *, /).
 * Normalizes thousands separators and commas.
 *
 * @param {string} expr
 * @returns {{ value: number | null, expression: string | null, terms: Array<{ op: string, value: number }> }}
 */
export function evaluateMathExpression(expr) {
  if (!expr || typeof expr !== "string") {
    return { value: null, expression: null, terms: [] };
  }

  // 1. Remove currency symbols and abbreviations
  let clean = expr
    .trim()
    .replace(/(?:₽|руб(?:л[ейя])?|р(?=\s|$)|rur|rub)/gi, "")
    .replace(/,/g, ".");

  // 2. Normalize spaces within numbers: '1 500' -> '1500'
  clean = normalizeNumberSpaces(clean);

  // 3. Remove words containing both letters and digits (without spaces) so they are not parsed as math numbers:
  // e.g. "iphone13", "100k", "кв12", "a1", "iphone-13"
  clean = clean.replace(
    /(?:^|(?<=[^a-zA-Zа-яёА-ЯЁ0-9_]))(?=[a-zA-Zа-яёА-ЯЁ0-9_-]*[a-zA-Zа-яёА-ЯЁ])(?=[a-zA-Zа-яёА-ЯЁ0-9_-]*\d)[a-zA-Zа-яёА-ЯЁ0-9_-]+(?![a-zA-Zа-яёА-ЯЁ0-9_])/gi,
    " ",
  );

  // 4. Match arithmetic tokens
  const tokens = clean.match(
    /(?:(?<![a-zA-Zа-яёА-ЯЁ0-9_])\d+(?:\.\d+)?(?![a-zA-Zа-яёА-ЯЁ0-9_])|[+\-*/])/g,
  );
  if (!tokens || tokens.length === 0) {
    return { value: null, expression: null, terms: [] };
  }

  const parsed = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (["+", "-", "*", "/"].includes(t)) {
      parsed.push(t);
    } else {
      const num = Number.parseFloat(t);
      if (!Number.isNaN(num)) {
        parsed.push(num);
      }
    }
  }

  if (parsed.length === 0 || typeof parsed[0] !== "number") {
    return { value: null, expression: null, terms: [] };
  }

  // First pass: Handle * and /
  const afterMulDiv = [];
  let i = 0;
  while (i < parsed.length) {
    const token = parsed[i];
    if (token === "*" || token === "/") {
      const prevNum = afterMulDiv.pop();
      const nextNum = parsed[i + 1];
      if (typeof prevNum === "number" && typeof nextNum === "number") {
        const res = token === "*" ? prevNum * nextNum : nextNum !== 0 ? prevNum / nextNum : prevNum;
        afterMulDiv.push(res);
        i += 2;
        continue;
      }
    }
    afterMulDiv.push(token);
    i++;
  }

  // Second pass: Handle + and -
  let total = typeof afterMulDiv[0] === "number" ? afterMulDiv[0] : 0;
  let currentOp = "+";
  const numCount = parsed.filter((t) => typeof t === "number").length;
  const terms = [{ op: "+", value: typeof afterMulDiv[0] === "number" ? afterMulDiv[0] : 0 }];

  for (let j = 1; j < afterMulDiv.length; j++) {
    const token = afterMulDiv[j];
    if (token === "+" || token === "-") {
      currentOp = token;
    } else if (typeof token === "number") {
      if (currentOp === "+") total += token;
      else if (currentOp === "-") total -= token;
      terms.push({ op: currentOp, value: token });
    }
  }

  if (numCount === 0) {
    return { value: null, expression: null, terms: [] };
  }

  total = Math.round(total * 100) / 100;

  return {
    value: total > 0 ? total : null,
    expression: numCount > 1 ? expr.trim() : null,
    terms,
  };
}

/**
 * Clean category suggestions with exact, prefix, word, and alias matching.
 *
 * @param {string} prefix
 * @param {Array<{ id: number, name: string, type: string }>} categories
 * @returns {Array<any>}
 */
export function getCategorySuggestions(prefix, categories = []) {
  if (!categories?.length) return [];
  const sorted = sortCategoriesByPopularity(categories);
  if (!prefix?.trim()) {
    return sorted.map((c) => ({
      ...c,
      matchedAlias: null,
    }));
  }

  const p = prefix.trim().toLowerCase();
  const startsWithName = [];
  const wordsStartWithName = [];
  const aliasMatch = [];
  const includesName = [];

  for (const cat of sorted) {
    const name = cat.name.toLowerCase();
    const catWords = name.split(/\s+/).filter((w) => w.length >= 2 && w !== "и");
    const aliases = (CATEGORY_ALIASES[cat.name] || []).map((a) => a.toLowerCase());

    // 1. Starts with category name
    if (name.startsWith(p)) {
      startsWithName.push({
        ...cat,
        matchedAlias: null,
      });
      continue;
    }

    // 2. Distinct words in name start with prefix
    const matchedWord = catWords.find((w) => w.startsWith(p));
    if (matchedWord) {
      wordsStartWithName.push({
        ...cat,
        matchedAlias: cat.name,
      });
      continue;
    }

    // 3. Alias match (startsWith or includes)
    const exactAlias = aliases.find((a) => a.startsWith(p));
    if (exactAlias) {
      aliasMatch.push({
        ...cat,
        matchedAlias: exactAlias,
      });
      continue;
    }

    const incAlias = aliases.find((a) => a.includes(p));
    if (incAlias) {
      aliasMatch.push({
        ...cat,
        matchedAlias: incAlias,
      });
      continue;
    }

    // 4. Category name includes prefix
    if (name.includes(p)) {
      includesName.push({
        ...cat,
        matchedAlias: null,
      });
    }
  }

  // Deduplicate preserving ranking order
  const seen = new Set();
  const results = [];
  for (const item of [...startsWithName, ...wordsStartWithName, ...aliasMatch, ...includesName]) {
    if (!seen.has(item.id)) {
      seen.add(item.id);
      results.push(item);
    }
  }

  return results;
}

